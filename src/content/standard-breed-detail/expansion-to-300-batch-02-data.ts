const appendParticle = (name: string, withFinal: string, withoutFinal: string) => {
  const last = name.charCodeAt(name.length - 1);
  return `${name}${last >= 0xac00 && last <= 0xd7a3 && (last - 0xac00) % 28 !== 0 ? withFinal : withoutFinal}`;
};

